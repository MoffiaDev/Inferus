using Content.Client.Administration.Managers;
using Content.Client.Audio;
using Content.Shared._Inferus.CCVar; // Inferus
using Content.Shared._Starlight.CCVar; // Inferus
using Content.Shared.CCVar;
using Robust.Client.Audio;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls; // Inferus
using Robust.Client.UserInterface.XAML;
using Robust.Shared;
using Robust.Shared.Configuration;

namespace Content.Client.Options.UI.Tabs;

[GenerateTypedNameReferences]
public sealed partial class AudioTab : Control
{
    [Dependency] private IAudioManager _audio = default!;
    [Dependency] private IClientAdminManager _admin = default!;
    [Dependency] private IConfigurationManager _cfg = default!;

    public AudioTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        // Begin Inferus - one sub-tab per group of options instead of one long column.
        AddSection(MusicPage, "ui-options-music-label");
        AddSection(EnvironmentPage, "ui-options-environment-label");
        AddSection(VoicesPage, "ui-options-voices-label");
        AddSection(OtherPage, "ui-options-other-label");
        AddSection(DevicePage, "ui-options-device-label");
        Pages.Orphan();
        CollectSectionButtons();
        // End Inferus

        Control.AddOptionDropDown(CVars.AudioDevice, DropDownAudioDevice, BuildAudioDeviceOptions());

        var masterVolume = Control.AddOptionPercentSlider(
            CVars.AudioMasterVolume,
            SliderVolumeMaster,
            scale: ContentAudioSystem.MasterVolumeMultiplier);
        masterVolume.ImmediateValueChanged += OnMasterVolumeSliderChanged;

        Control.AddOptionPercentSlider(
            CVars.MidiVolume,
            SliderVolumeMidi,
            scale: ContentAudioSystem.MidiVolumeMultiplier);

        Control.AddOptionPercentSlider(
            CCVars.AmbientMusicVolume,
            SliderVolumeAmbientMusic,
            scale: ContentAudioSystem.AmbientMusicMultiplier);

        Control.AddOptionPercentSlider(
            CCVars.AmbienceVolume,
            SliderVolumeAmbience,
            scale: ContentAudioSystem.AmbienceMultiplier);

        Control.AddOptionPercentSlider(
            CCVars.LobbyMusicVolume,
            SliderVolumeLobby,
            scale: ContentAudioSystem.LobbyMultiplier);

        Control.AddOptionPercentSlider(
            CCVars.InterfaceVolume,
            SliderVolumeInterface,
            scale: ContentAudioSystem.InterfaceMultiplier);

        Control.AddOptionPercentSlider(InferusCCVars.SpeechBlipVolume, SliderVolumeSpeechBlip); // Inferus
        Control.AddOptionPercentSlider(StarlightCCVars.ReverbVolume, SliderReverb); // Inferus

        Control.AddOptionSlider(
            CCVars.MaxAmbientSources,
            SliderMaxAmbienceSounds,
            _cfg.GetCVar(CCVars.MinMaxAmbientSourcesConfigured),
            _cfg.GetCVar(CCVars.MaxMaxAmbientSourcesConfigured));

        Control.AddOptionCheckBox(CCVars.LobbyMusicEnabled, LobbyMusicCheckBox);
        Control.AddOptionCheckBox(CCVars.RestartSoundsEnabled, RestartSoundsCheckBox);
        Control.AddOptionCheckBox(CCVars.EventMusicEnabled, EventMusicCheckBox);
        Control.AddOptionCheckBox(CCVars.AdminSoundsEnabled, AdminSoundsCheckBox);
        Control.AddOptionCheckBox(CCVars.BwoinkSoundEnabled, BwoinkSoundCheckBox);
        Control.AddOptionCheckBox(CCVars.AudioHrtf, AudioHrtfCheckBox);
        Control.AddOptionCheckBox(CVars.AudioMuteUnfocused, MuteUnfocusedCheckBox);

        Control.Initialize();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _admin.AdminStatusUpdated += UpdateAdminButtonsVisibility;
        UpdateAdminButtonsVisibility();
        RestoreSectionButtons(); // Inferus
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _admin.AdminStatusUpdated -= UpdateAdminButtonsVisibility;
    }


    private void UpdateAdminButtonsVisibility()
    {
        BwoinkSoundCheckBox.Visible = _admin.IsActive();
    }

    private void OnMasterVolumeSliderChanged(float value)
    {
        // TODO: I was thinking of giving OptionsTabControlRow a flag to "set CVar immediately", but I'm deferring that
        // until there's a proper system for enforcing people don't close the window with pending changes.
        _audio.SetMasterGain(value);
    }

    private List<OptionDropDownCVar<string>.ValueOption> BuildAudioDeviceOptions()
    {
        var options = new List<OptionDropDownCVar<string>.ValueOption>();

        options.Add(new OptionDropDownCVar<string>.ValueOption(
            string.Empty,
            Loc.GetString("ui-options-audio-device-default")));

        foreach (var device in _audio.GetAudioDevices())
        {
            options.Add(new OptionDropDownCVar<string>.ValueOption(device, FormatAudioDeviceLabel(device)));
        }

        return options;
    }

    private static string FormatAudioDeviceLabel(string device)
    {
        const string openAlSoftPrefix = "OpenAL Soft on ";
        if (device.StartsWith(openAlSoftPrefix, StringComparison.Ordinal))
            return IAudioManager.ConvertAudioDeviceNameForDisplay(device);

        return device;
    }

    // Begin Inferus
    private readonly List<Control> _sectionPages = [];
    private readonly List<BaseButton> _sectionButtons = [];
    private ButtonGroup? _sectionGroup;

    private void AddSection(Control page, string title)
    {
        page.Orphan();
        page.Margin = new Thickness(4);
        Sections.AddTab(page, Loc.GetString(title));
        _sectionPages.Add(page);
    }

    private void CollectSectionButtons()
    {
        // The first scroll container holds the tab buttons, the second one the pages.
        foreach (var child in Sections.Children)
        {
            if (child is not ScrollContainer)
                continue;

            CollectSectionButtons(child);
            break;
        }
    }

    private void CollectSectionButtons(Control parent)
    {
        foreach (var child in parent.Children)
        {
            if (child is BaseButton { Group: { } group } button)
            {
                _sectionGroup ??= group;
                _sectionButtons.Add(button);
            }
            else
            {
                CollectSectionButtons(child);
            }
        }
    }

    private void RestoreSectionButtons()
    {
        if (_sectionGroup == null)
            return;

        foreach (var button in _sectionButtons)
        {
            button.Group = _sectionGroup;
        }

        for (var i = 0; i < _sectionPages.Count && i < _sectionButtons.Count; i++)
        {
            if (_sectionPages[i].Visible)
                _sectionButtons[i].Pressed = true;
        }
    }
    // End Inferus
}

using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Starlight.Lobby.UI;

[GenerateTypedNameReferences]
public sealed partial class CharacterInfoEditor : Control
{
    public CharacterInfoEditor()
    {
        RobustXamlLoader.Load(this);

        SetPlaceholder(PhysicalDescInput, "character-physical-text-placeholder");
        SetPlaceholder(PersonalityDescInput, "character-personality-text-placeholder");
    }

    private static void SetPlaceholder(TextEdit control, string locId)
        => control.Placeholder = new Rope.Leaf(Loc.GetString(locId));
}

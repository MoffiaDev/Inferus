using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Starlight.Character.Info.UI;

[GenerateTypedNameReferences]
public sealed partial class CharacterInspectWindow : FancyWindow
{
    public CharacterInspectWindow()
    {
        RobustXamlLoader.Load(this);
        InspectTabs.SetTabTitle(0, Loc.GetString("character-info-ic"));
        InspectTabs.SetTabTitle(1, Loc.GetString("character-info-ooc"));
        // Inferus - no background tab
        OnClose += ClearCharacter;
    }

    public void SetCharacter(EntityUid? entityUid, IEntityManager entityManager, EntityUid viewer)
    {
        ICInfo.SetCharacter(entityUid, entityManager, viewer);
        OOCInfo.SetCharacter(entityUid, entityManager, viewer);
    }

    // Inferus - fills in the mind-held info the server sent for another player's character
    public void SetMindInfo(string personalityDescription, string oocNotes)
    {
        ICInfo.SetPersonalityDescription(personalityDescription);
        OOCInfo.SetOOCNotes(oocNotes);
    }
    // End Inferus

    public void ClearCharacter()
    {
        ICInfo.ClearCharacter();
        OOCInfo.ClearCharacter();
    }
}

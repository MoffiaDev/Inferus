using Content.Shared._Starlight.Character.Info.Components;
using Content.Shared.Mind;
using Content.Shared.Roles.Jobs;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Starlight.Character.Info.UI;

[GenerateTypedNameReferences]
public sealed partial class CharacterICInfoControl : Control
{
    public CharacterICInfoControl()
        => RobustXamlLoader.Load(this);

    public void SetCharacter(EntityUid? target, IEntityManager entityManager, EntityUid viewer)
    {
        if (!target.HasValue)
        {
            ClearCharacter();
            return;
        }

        var mind = entityManager.System<SharedMindSystem>().GetMind(target.Value);

        CharacterView.SetCharacter(target,
            entityManager.System<SharedJobSystem>().MindTryGetJobName(mind, out var jobName)
                ? jobName
                : string.Empty,
            viewer);

        _physicalDescription = string.Empty;
        _personalityDescription = string.Empty;
        if (entityManager.TryGetComponent(target.Value, out CharacterDescriptionComponent? charDesc))
            _physicalDescription = charDesc.Description;

        if (mind.HasValue && entityManager.TryGetComponent(mind.Value, out CharacterDescriptionComponent? mindDesc))
            _personalityDescription = mindDesc.Description;

        UpdateDescription();
    }

    // Inferus - the personality description lives on the mind, which the server sends separately for other players
    private string _physicalDescription = string.Empty;
    private string _personalityDescription = string.Empty;

    public void SetPersonalityDescription(string personalityDescription)
    {
        _personalityDescription = personalityDescription;
        UpdateDescription();
    }

    private void UpdateDescription()
    {
        var desc = _physicalDescription;
        if (desc.Length > 0 && _personalityDescription.Length > 0)
            desc += "\n";
        desc += _personalityDescription;

        CharacterDesc.SetMessage(FormattedMessage.RemoveMarkupPermissive(desc));
        CharacterDesc.InvalidateMeasure();
    }
    // End Inferus

    public void ClearCharacter()
    {
        CharacterView.ClearCharacter();
        CharacterDesc.Text = null;
        _physicalDescription = string.Empty; // Inferus
        _personalityDescription = string.Empty; // Inferus
    }
}

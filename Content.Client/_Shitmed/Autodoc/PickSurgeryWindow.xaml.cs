using Content.Client.UserInterface.Controls;
using Content.Shared._Shitmed.Autodoc;
using Content.Shared._Shitmed.Surgery.Operations;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Shitmed.Autodoc;

[GenerateTypedNameReferences]
public sealed partial class PickSurgeryWindow : FancyWindow
{
    private static readonly string[] Categories =
    [
        "Head", "Torso", "ArmLeft", "ArmRight", "HandLeft", "HandRight", "LegLeft", "LegRight", "FootLeft", "FootRight"
    ];

    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IComponentFactory _factory = default!;

    public event Action<IAutodocStep>? OnAddStep;

    private string? _part;
    private EntProtoId<SurgeryComponent>? _surgeryId;

    public PickSurgeryWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        OnAddStep += _ => Close();

        // the limb is chosen by its category, which already says left or right
        Symmetry.Visible = false;

        foreach (var category in Categories)
        {
            Parts.AddItem(Loc.GetString("autodoc-organ-category-" + category), metadata: category);
        }

        Parts.OnItemSelected += args =>
        {
            if (Parts[args.ItemIndex].Metadata is not string part)
                return;

            _part = part;
            UpdateSubmit();
        };
        Parts.OnItemDeselected += _ =>
        {
            _part = null;
            SubmitButton.Disabled = true;
        };

        Surgeries.OnItemSelected += args =>
        {
            if (Surgeries[args.ItemIndex].Metadata is not EntProtoId<SurgeryComponent> id)
                return;

            _surgeryId = id;
            UpdateSubmit();
        };
        Surgeries.OnItemDeselected += _ =>
        {
            _surgeryId = null;
            SubmitButton.Disabled = true;
        };

        SubmitButton.OnPressed += _ =>
        {
            var step = new SurgeryAutodocStep()
            {
                Part = _part!,
                Surgery = _surgeryId!.Value
            };
            OnAddStep?.Invoke(step);
        };

        UpdateSurgeries();
    }

    // every surgery is listed, the server turns down the ones that do not fit the limb when the program runs
    private void UpdateSurgeries()
    {
        Surgeries.Clear();

        foreach (var proto in _proto.EnumeratePrototypes<EntityPrototype>())
        {
            if (proto.Abstract || !proto.TryGetComponent<SurgeryComponent>(out _, _factory))
                continue;

            Surgeries.AddItem(proto.Name, metadata: new EntProtoId<SurgeryComponent>(proto.ID));
        }

        Surgeries.SortItemsByText();
    }

    private void UpdateSubmit()
    {
        SubmitButton.Disabled = _part == null || _surgeryId == null;
    }
}
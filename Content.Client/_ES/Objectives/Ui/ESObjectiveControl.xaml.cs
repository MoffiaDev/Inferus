using Content.Client.Message;
using Content.Shared.Objectives;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._ES.Objectives.Ui;

/// <summary>
/// Displays a single objective in the <see cref="Content.Client._ES.Mind.Ui.ESCharacterWindow"/>.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ESObjectiveControl : BoxContainer
{
    [Dependency] private IEntityManager _ent = default!;

    private readonly SpriteSystem _sprite;

    public ESObjectiveControl()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _sprite = _ent.System<SpriteSystem>();
    }

    // Inferus - uses the stock objective info sent by the server instead of ES objective entities.
    public void SetObjective(ObjectiveInfo objective)
    {
        TitleLabel.SetMarkup(Loc.GetString("es-character-window-objective-title-fmt",
            ("title", FormattedMessage.EscapeText(objective.Title))));
        DescriptionLabel.SetMarkup(Loc.GetString("es-character-window-objective-desc-fmt",
            ("text", FormattedMessage.EscapeText(objective.Description))));

        Icon.Texture = _sprite.Frame0(objective.Icon);
        Icon.Progress = objective.Progress;
    }
}

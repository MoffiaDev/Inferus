using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;

namespace Content.Client._ES.Spawning.Ui;

[GenerateTypedNameReferences]
public sealed partial class ESStationCheckbox : BoxContainer
{
    public event Action<NetEntity>? OnPressed;

    // Inferus - stations are tracked by NetEntity, since station entities aren't guaranteed to exist on the client in the lobby.
    public NetEntity Station { get; private set; }

    public bool Pressed => CheckBox.Pressed;

    public ESStationCheckbox()
    {
        RobustXamlLoader.Load(this);
    }

    public ESStationCheckbox(NetEntity station, string stationName)
    {
        RobustXamlLoader.Load(this);

        CheckBox.OnPressed += _ =>
        {
            OnPressed?.Invoke(station);
        };
        StationLabel.Text = stationName;
        Station = station;
    }

    /// <summary>
    /// Sets the pressed state without playing a click sound or raising <see cref="OnPressed"/>.
    /// </summary>
    public void SetPressedSilent(bool value)
    {
        CheckBox.Pressed = value;
    }

    public void SetClickPressed(bool value)
    {
        CheckBox.SetClickPressed(value);
        OnPressed?.Invoke(Station);
    }

    protected override void KeyBindDown(GUIBoundKeyEventArgs args)
    {
        base.KeyBindDown(args);

        if (args.Handled || args.Function != EngineKeyFunctions.UIClick)
            return;

        SetClickPressed(!CheckBox.Pressed);
    }
}

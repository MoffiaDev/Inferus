using System.Linq;
using Content.Client._ES.Objectives.Ui;
using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared.Mind;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;
using static Content.Client.CharacterInfo.CharacterInfoSystem;

namespace Content.Client._ES.Mind.Ui;

/// <summary>
/// Character menu showing the player's role type, character, job, briefing and objectives.
/// Replaces <see cref="Content.Client.UserInterface.Systems.Character.Windows.CharacterWindow"/>.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ESCharacterWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototype = default!;

    public ESCharacterWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        InfoBlurbText.Visible = false;
        ExtraInfoContainer.Visible = false;
    }

    // Inferus - fed by the stock CharacterInfoSystem rather than ES masks and objectives.
    public void Update(CharacterData data, List<Control> extraControls)
    {
        var (entity, objectives, briefing, jobId, entityName) = data;

        SelfView.SetEntity(entity);

        NameLabel.SetMarkup(Loc.GetString("es-character-window-name-fmt",
            ("name", FormattedMessage.EscapeText(entityName))));

        if (jobId != null && _prototype.TryIndex(jobId, out var job))
        {
            JobLabel.SetMarkup(Loc.GetString("es-character-window-job-fmt", ("name", job.LocalizedName)));
            JobLabel.Visible = true;
        }
        else
        {
            JobLabel.Visible = false;
        }

        if (!string.IsNullOrWhiteSpace(briefing))
        {
            InfoBlurbText.SetMarkup(Loc.GetString("es-character-window-briefing-fmt",
                ("text", FormattedMessage.EscapeText(briefing))));
            InfoBlurbText.Visible = true;
        }
        else
        {
            InfoBlurbText.Visible = false;
        }

        ExtraInfoContainer.RemoveAllChildren();
        foreach (var control in extraControls)
        {
            ExtraInfoContainer.AddChild(control);
        }
        ExtraInfoContainer.Visible = extraControls.Count > 0;

        ObjectivesContainer.RemoveAllChildren();
        foreach (var (issuer, conditions) in objectives)
        {
            if (conditions.Count == 0)
                continue;

            var issuerLabel = new RichTextLabel();
            issuerLabel.SetMarkup(Loc.GetString("es-character-window-objective-issuer-fmt",
                ("issuer", FormattedMessage.EscapeText(issuer))));
            ObjectivesContainer.AddChild(issuerLabel);

            foreach (var condition in conditions)
            {
                var control = new ESObjectiveControl();
                control.SetObjective(condition);
                ObjectivesContainer.AddChild(control);
            }
        }

        ObjectivesPlaceholder.Visible = !objectives.Values.Any(c => c.Count > 0);
    }

    public void SetRoleType(RoleTypePrototype? roleType)
    {
        var name = Loc.GetString(roleType?.Name ?? RoleTypePrototype.FallbackName);
        var color = roleType?.Color ?? RoleTypePrototype.FallbackColor;

        RoleTypeLabel.SetMarkup(Loc.GetString("es-character-window-role-type-fmt",
            ("name", name),
            ("color", color.ToHex())));
    }
}
